import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
const source = readFileSync(new URL("../app.js", import.meta.url), "utf8");
const start = source.indexOf("function scheduleDisplayRowV165(");
const end = source.indexOf("const tableBeforeParityV165", start);
assert.ok(start >= 0 && end > start);
const project = vm.runInNewContext(`${source.slice(start, end)}; scheduleDisplayRowV165`, { Date });
const mixed = Object.freeze({ id: "legacy", name: "Mixed", startAt: "2026-11-14T11:00:00+09:00", description: "memo", unknown: Object.freeze({ preserve: true }) });
const projected = project(mixed);
assert.equal(projected.title, "Mixed");
assert.equal(projected.memo, "memo");
assert.equal(projected.id, mixed.id);
assert.equal(projected.unknown, mixed.unknown);
assert.equal(mixed.title, undefined);
const date = new Date(mixed.startAt);
assert.equal(projected.start_time, `${String(date.getHours()).padStart(2, "0")}:${String(date.getMinutes()).padStart(2, "0")}`);
const canonical = project({ ...mixed, title: "Canonical", date: "2026-11-15", start_time: "09:00", memo: "canonical" });
assert.equal(canonical.title, "Canonical"); assert.equal(canonical.date, "2026-11-15");
assert.equal(canonical.start_time, "09:00"); assert.equal(canonical.memo, "canonical");
assert.equal(project({ name: "Invalid date", startAt: "not a date" }).date, "");
assert.equal(project({ name: "Invalid date", startAt: "not a date" }).start_time, "");
console.log("PASS mixed schedule projection: source immutable, canonical precedence, local timestamp, invalid-date handling");
