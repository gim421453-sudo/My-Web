import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { buildG2BRecoveryAnchor, createG2BRecoveryAnchorStore, prepareG2BFutureM3Anchor } from "../authority-audit/g2bRecoveryAnchor.mjs";

const directory = mkdtempSync(join(tmpdir(), "myweb-new-generation-"));
const store = createG2BRecoveryAnchorStore({ directory });
const secret = randomBytes(32);
const keyId = randomUUID();
const oldId = randomUUID();
const newId = randomUUID();
const old = buildG2BRecoveryAnchor({ member: "serviceAccount:old@example.invalid", secret, secretKeyId: keyId, operationGenerationId: oldId });
assert.equal(store.create(old).ok, true);
assert.equal(store.transition(oldId, "ANCHOR_PERSISTED", "ANCHOR_VERIFIED").ok, true);
assert.equal(store.transition(oldId, "ANCHOR_VERIFIED", "MUTATION_STARTED").ok, true);
assert.equal(store.transition(oldId, "MUTATION_STARTED", "MUTATION_INDETERMINATE").ok, true);
assert.equal(store.transition(oldId, "MUTATION_INDETERMINATE", "RECOVERY_CONFIRMED_ABSENT").ok, true);
const provider = { loadOrInitialize: () => ({ state: "READY", secret, keyId }) };
const identity = { exactIamMember: "serviceAccount:new@example.invalid" };
const next = prepareG2BFutureM3Anchor({ identityContext: identity, secretProvider: provider, store, operationGenerationId: newId });
assert.equal(next.mutationReachable, true);
assert.equal(next.operationGenerationId, newId);
assert.notEqual(next.operationGenerationId, oldId);
assert.equal(store.load(oldId).record.anchorState, "RECOVERY_CONFIRMED_ABSENT");
assert.equal(prepareG2BFutureM3Anchor({ identityContext: identity, secretProvider: provider, store, operationGenerationId: oldId }).mutationReachable, false, "old terminal anchor cannot authorize new generation");
rmSync(directory, { recursive: true, force: true });
console.log("G2B new generation isolation passed; terminal anchors cannot be reused and secret domain separation is operation-specific");
