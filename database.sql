create or replace function is_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists(select 1 from profiles where id = auth.uid() and role = 'admin');
$$;

-- 핵심 정책 예시: 관리자는 전체 접근, 일반 사용자는 공개 데이터와 본인 데이터 중심.
create policy "profiles own read" on profiles for select using (id = auth.uid() or is_admin());
create policy "profiles admin write" on profiles for all using (is_admin()) with check (is_admin());

create policy "admin all teachers" on teachers for all using (is_admin()) with check (is_admin());
create policy "admin all people" on people for all using (is_admin()) with check (is_admin());
create policy "public subjects read" on subjects for select using (true);
create policy "admin subjects write" on subjects for all using (is_admin()) with check (is_admin());

create policy "own schedules read" on schedules for select using (user_id = auth.uid() or is_admin());
create policy "admin schedules write" on schedules for all using (is_admin()) with check (is_admin());

create policy "own attendance read" on attendance for select using (user_id = auth.uid() or is_admin());
create policy "attendance insert own or admin" on attendance for insert with check (user_id = auth.uid() or is_admin());
create policy "admin attendance update" on attendance for update using (is_admin()) with check (is_admin());
create policy "admin attendance delete" on attendance for delete using (is_admin());

create policy "own penalty read" on penalty_records for select using (user_id = auth.uid() or is_admin());
create policy "admin penalty write" on penalty_records for all using (is_admin()) with check (is_admin());

create policy "visible notices read" on notices for select using (visibility = '일반 공개' or is_admin());
create policy "admin notices write" on notices for all using (is_admin()) with check (is_admin());

create policy "visible files read" on files for select using (visibility = '일반 공개' or is_admin());
create policy "admin files write" on files for all using (is_admin()) with check (is_admin());

create policy "visible portfolios read" on portfolios for select using (visibility = '일반 공개' or is_admin());
create policy "admin portfolios write" on portfolios for all using (is_admin()) with check (is_admin());

create policy "own study logs read" on study_logs for select using (user_id = auth.uid() or is_admin());
create policy "own study logs write" on study_logs for all using (user_id = auth.uid() or is_admin()) with check (user_id = auth.uid() or is_admin());

create policy "admin backups all" on backups for all using (is_admin()) with check (is_admin());
create policy "own exams read" on exams for select using (user_id = auth.uid() or is_admin());
create policy "admin exams write" on exams for all using (is_admin()) with check (is_admin());
create policy "own assignments read" on assignments for select using (user_id = auth.uid() or is_admin());
create policy "own assignments write" on assignments for all using (user_id = auth.uid() or is_admin()) with check (user_id = auth.uid() or is_admin());
