-- Supabase/PostgreSQL 설계 초안
-- 실제 배포 시 Supabase Auth의 auth.users와 public.profiles를 연결해 사용하세요.

create type app_role as enum ('admin', 'user', 'print');
create type visibility_type as enum ('일반 공개', '관리자 전용', '비공개');

create table profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  role app_role not null default 'user',
  pin_hash text,
  created_at timestamptz not null default now()
);

create table teachers (
  id bigint generated by default as identity primary key,
  name text not null,
  subject text,
  type text,
  phone text,
  email text,
  memo text,
  private_memo text,
  created_at timestamptz not null default now()
);

create table subjects (
  id bigint generated by default as identity primary key,
  name text not null,
  teacher_id bigint references teachers(id) on delete set null,
  location text,
  schedule_text text,
  memo text,
  created_at timestamptz not null default now()
);

create table schedules (
  id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete cascade,
  title text not null,
  date date not null,
  start_time time,
  end_time time,
  type text,
  importance text,
  status text,
  memo text,
  attachment_link text,
  created_at timestamptz not null default now()
);

create table attendance (
  id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete cascade,
  subject_id bigint references subjects(id) on delete set null,
  date date not null,
  class_type text,
  status text,
  reason text,
  admin_memo text,
  created_at timestamptz not null default now()
);

create table penalty_records (
  id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete cascade,
  date date not null,
  title text not null,
  points integer not null default 0,
  reason text,
  place text,
  status text,
  admin_memo text,
  created_at timestamptz not null default now()
);

create table notices (
  id bigint generated by default as identity primary key,
  title text not null,
  content text,
  source text,
  subject_id bigint references subjects(id) on delete set null,
  importance text,
  notice_date date,
  attachment_link text,
  is_checked boolean not null default false,
  visibility visibility_type not null default '일반 공개',
  created_at timestamptz not null default now()
);

create table files (
  id bigint generated by default as identity primary key,
  title text not null,
  file_type text,
  category text,
  subject_id bigint references subjects(id) on delete set null,
  google_drive_link text,
  local_backup_path text,
  tags text,
  visibility visibility_type not null default '일반 공개',
  is_backed_up boolean not null default false,
  created_at timestamptz not null default now()
);

create table people (
  id bigint generated by default as identity primary key,
  name text not null,
  birthday date,
  phone text,
  email text,
  organization text,
  relationship text,
  memo text,
  private_memo text,
  created_at timestamptz not null default now()
);

create table portfolios (
  id bigint generated by default as identity primary key,
  title text not null,
  category text,
  date date,
  description text,
  skills text,
  file_link text,
  image_link text,
  video_link text,
  result_link text,
  reflection text,
  visibility visibility_type not null default '일반 공개',
  is_featured boolean not null default false,
  created_at timestamptz not null default now()
);

create table study_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete cascade,
  subject_id bigint references subjects(id) on delete set null,
  date date not null,
  start_time time,
  end_time time,
  total_minutes integer,
  content text,
  focus_level text,
  is_reviewed boolean not null default false,
  memo text,
  created_at timestamptz not null default now()
);

create table backups (
  id bigint generated by default as identity primary key,
  backup_type text,
  date date,
  target text,
  status text,
  memo text,
  created_at timestamptz not null default now()
);

create table exams (
  id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete cascade,
  subject_id bigint references subjects(id) on delete set null,
  title text not null,
  date date,
  score numeric,
  average numeric,
  analysis text,
  file_link text,
  created_at timestamptz not null default now()
);

create table assignments (
  id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete cascade,
  subject_id bigint references subjects(id) on delete set null,
  title text not null,
  place text,
  due_date date,
  content text,
  memo text,
  source text,
  file_link text,
  importance text,
  is_checked boolean not null default false,
  created_at timestamptz not null default now()
);

